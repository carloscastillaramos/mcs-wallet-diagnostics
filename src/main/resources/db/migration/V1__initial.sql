-- PostgreSQL 16+, schema wallet_diagnostics controlled by Flyway.
CREATE TABLE mcs_diag_device (
    device_id           varchar(36) NOT NULL,
    key_id              varchar(64) NOT NULL,
    platform            varchar(10) NOT NULL CHECK (platform IN ('ANDROID','IOS')),
    public_key_spki_b64 varchar(2048) NOT NULL,
    active              boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at          timestamptz,
    CONSTRAINT mcs_diag_device_pk PRIMARY KEY (device_id, key_id)
);

CREATE TABLE mcs_diag_nonce (
    device_id    varchar(36) NOT NULL,
    nonce_value  varchar(96) NOT NULL,
    received_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT mcs_diag_nonce_pk PRIMARY KEY (device_id, nonce_value)
);
CREATE INDEX mcs_diag_nonce_age_idx ON mcs_diag_nonce (received_at);

-- Retain globally unique (device_id,event_id) even across month partitions.
-- The registry and the partitioned event row are inserted in one transaction.
CREATE TABLE mcs_diag_event_registry (
    device_id      varchar(36) NOT NULL,
    event_id       varchar(36) NOT NULL,
    payload_sha256 char(64) NOT NULL,
    first_seen_at  timestamptz NOT NULL,
    CONSTRAINT mcs_diag_event_registry_pk PRIMARY KEY (device_id, event_id)
) PARTITION BY HASH (device_id);
-- Fixed-size hash partitions distribute the global dedup registry by device.
-- Because device_id is part of the PK, uniqueness is guaranteed across all events.
DO $block$
BEGIN
    FOR i IN 0..15 LOOP
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF mcs_diag_event_registry FOR VALUES WITH (MODULUS 16, REMAINDER %s)',
            'mcs_diag_event_registry_h' || lpad(i::text, 2, '0'), i
        );
    END LOOP;
END
$block$;
CREATE INDEX mcs_diag_registry_age_idx ON mcs_diag_event_registry (first_seen_at);

CREATE TABLE mcs_diag_event (
    device_id        varchar(36) NOT NULL,
    event_id         varchar(36) NOT NULL,
    occurred_at      timestamptz NOT NULL,
    received_at      timestamptz NOT NULL,
    event_type       varchar(48) NOT NULL,
    component        varchar(48) NOT NULL,
    severity         varchar(10) NOT NULL CHECK (severity IN ('INFO','WARN','ERROR','CRITICAL')),
    error_code       varchar(64) NOT NULL,
    platform         varchar(10) NOT NULL CHECK (platform IN ('ANDROID','IOS')),
    app_version      varchar(32) NOT NULL,
    duration_ms      bigint,
    attributes_json  jsonb,
    payload_sha256   char(64) NOT NULL,
    CONSTRAINT mcs_diag_event_pk PRIMARY KEY (device_id, event_id, received_at)
) PARTITION BY RANGE (received_at);
CREATE INDEX mcs_diag_event_time_idx ON mcs_diag_event (received_at DESC, event_id DESC);
CREATE INDEX mcs_diag_event_code_idx ON mcs_diag_event (error_code, received_at DESC);
CREATE INDEX mcs_diag_event_device_idx ON mcs_diag_event (device_id, received_at DESC);

CREATE TABLE mcs_diag_admin_audit (
    audit_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action      varchar(48) NOT NULL CHECK (action IN ('DEVICE_REGISTERED','DEVICE_REVOKED')),
    actor_id    varchar(200) NOT NULL,
    device_id   varchar(36) NOT NULL,
    key_id      varchar(64) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX mcs_diag_admin_audit_time_idx ON mcs_diag_admin_audit (created_at DESC);

-- Initial rolling horizon: previous month through 18 months ahead.
DO $block$
DECLARE
    month_start date := (date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date - INTERVAL '1 month')::date;
    partition_start date;
BEGIN
    FOR i IN 0..19 LOOP
        partition_start := (month_start + make_interval(months => i))::date;
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF mcs_diag_event FOR VALUES FROM (%L) TO (%L)',
            'mcs_diag_event_' || to_char(partition_start, 'YYYY_MM'),
            to_char(partition_start, 'YYYY-MM-DD') || ' 00:00:00+00',
            to_char((partition_start + interval '1 month')::date, 'YYYY-MM-DD') || ' 00:00:00+00'
        );
    END LOOP;
END
$block$;
